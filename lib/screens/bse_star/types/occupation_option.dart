class OccupationOptionsResponse {
    String message;
    List<Datum> data;

    OccupationOptionsResponse({
        required this.message,
        required this.data,
    });

    factory OccupationOptionsResponse.fromJson(Map<String, dynamic> json) => OccupationOptionsResponse(
        message: json["message"],
        data: List<Datum>.from(json["data"].map((x) => Datum.fromJson(x))),
    );

    Map<String, dynamic> toJson() => {
        "message": message,
        "data": List<dynamic>.from(data.map((x) => x.toJson())),
    };
}

class Datum {
    String id;
    String name;

    Datum({
        required this.id,
        required this.name,
    });

    factory Datum.fromJson(Map<String, dynamic> json) => Datum(
        id: json["id"],
        name: json["name"],
    );

    Map<String, dynamic> toJson() => {
        "id": id,
        "name": name,
    };
}
